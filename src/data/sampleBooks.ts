香港だかどこかの資産家の家訓に、女に惚れても男に惚れるな、というのがあるらしい。女に惚れて金を注ぎ込んでも1億円くらいを失うだけだが、男に惚れて事業に注ぎ込むと全財産を失うリスクがあるという戒め。

