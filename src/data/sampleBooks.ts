群れないこと、でも完全に一人にもならないこと。このバランスをどう取るかで、その人の成長の質は大きく変わる。本質に近づくための孤独と、人としての広がりを持つための繋がり。この両方を意識して持てるかどうかが、「本物」と呼ばれる領域に行けるかどうかの分かれ目になると思う。

