嫉妬されないっていうのも、成功には意外と重要なんだよね。人間って理屈じゃなくて感情で動くから。「あいつ気に食わないな」っていう感情一つで、流れが変わることも普通にある。特に同じ土俵にいる男同士だと、その傾向はより強く出る。だから、無駄に嫉妬を買わない立ち回りって、実はかなり重要なスキルなんよ。

女に惚れても、男に惚れるなという至言がある。女に惚れてカネを突っ込んでもたかが知れているけど、男に惚れると全財産を溶かすことってよくあるのよ。

