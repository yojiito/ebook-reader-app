起業したてで自分で営業してた頃、とても親切にしてくれた社長達は、まだ生き残っていて、酷い態度をとっていた人たちは全員いなくなるか、いるかいないか分からないレベルを彷徨っている。性格のいい人しか長期的には成功できないようになっていることを思い知るな。

短期的には、強引でも、横柄でも、勢いで伸びる人はいる。でもそれって続かないのよ。どこかで人が離れるし、どこかで歪みが出てくる。俺が起業したての頃、いろんな経営者にテレアポして、アポを取って、実際に会いに行ってたわけよ。そのときの社長たちの対応を今でも鮮明に覚えてるよ。

ある外食チェーンの社長なんかは、めちゃくちゃ丁寧に対応してくれて、「若いのに頑張ってるね」って感じでちゃんと話を聞いてくれた。ああいう人って、やっぱり今でもちゃんと残っているんだよ。逆に、しょうもない小物ほど対応がひどかったよね。最初から上から目線だったり、話もまともに聞かずにあしらったり。今振り返ると、大物ほど余裕があって優しいし、小物ほど余裕がなくて攻撃的なんだよ。もちろん、自分が気に入ってもらえたっていうのもあるとは思うよ。でも、それを差し引いても、人としての器の違いは明確にあった。

結局、商売って人で成り立ってるからね。どれだけ儲けるか以前に、「人からどう思われるか」が長期的には効いてくる。だから、どんな相手に対しても最低限のリスペクトを持つっていうのは、当たり前だけどめちゃくちゃ重要なんだよ。

28
女の嫉妬は家庭を滅ぼし、男の嫉妬は国を滅ぼす。とある上場企業オーナーがよく口にしていた言葉だ。男の嫉妬を絶対に甘くみてはならない。孫さんが小柄で禿げてなく、長身のイケメンだったら、あんな風になれなかったとマジで思う。

