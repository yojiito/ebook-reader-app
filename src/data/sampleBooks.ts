人生は先に苦労するか後で苦労するかみたいなところがあるんだよ。一つ言えるのは、晩年に向けて盛り上がっていく人生の方が絶対によいということ。若いうちに努力しておけよ。

若いときにピークを迎えて、あとは下り坂っていう人生って正直しんどいじゃない。だから、若いうちにしっかり努力しておけよって話になるの。若いときにサボって何も積み上げてこないと、年齢を重ねたときに打てる手が極端に少なくなる。ただ、サラリーマンって構造的にこういうメンタリティになりにくいんだよね。毎月給料が入ってくるし、大きく失敗しない限り、生活は守られるから。その分、「何かを成し遂げるためにリスクを取る」という発想が弱くなりやすい。もちろん、サラリーマンでもすごい人はいるよ。でも、「本気で何かを成し遂げたい」と思ったときに、ずっとその枠の中にいるのは難しいと思う。

どこかで勝負に出ないといけないタイミングが来る。そのときに動けるかどうかは、若い頃にどれだけ準備してきたかで決まる。結局、人生って積み上げだからね。どこで楽をするかじゃなくて、どこで負荷をかけるか。その選択で、後半の景色は大きく変わるよ。


24
人生は想い出づくりの場だとずっと言い続けてる。人間は感情が大きく動いたことが想い出になっていく。経営者が昔話をするとき、成功した話より苦労話の方が多くなるのがその証拠だ。傷つくことを過剰に恐れてはいけない。傷つかずに生きることと良い人生は絶対にイコールにならないよ。

人生の価値って、「どれだけ感情が動いたか」で決まると思うんだよ。

経営者が成功話より苦労話の方を熱く語りがちなのって、単純に強く記憶に残っているだけじゃなくて、そのときの感情の振れ幅が大きかったからなんだよね。順風満帆な話っ聞いてても面白くないし、あまり語る気にならないものなのよ。逆に、しんどかった話の方が、後からいくらでも語れる。だから、傷つくことを過剰に恐れてはいけない。傷つかずに生きることと、良い人生を送ることは絶対にイコールにならないから。

ただ、ここで重要なのが「どう終わるか」なんだよね。勝った人間が苦労話をすると、それは悲壮感のない武勇伝になる。「あのときマジでヤバかったんだよ」って笑いながら話せる。でも、本当に失敗して立ち直れなかった人が同じ話をすると、ただの重たい話で終わる。聞いてる側もどうリアクションしていいか分からないし、正直しんどい。だから、苦労すること自体はいいんだけど、最終的には成功しておかないとダメなんだよ。

人生は思い出作りが一番大事。でも、その思い出が「いい話」になるか「ただの悲劇」になるかは、最後にどう着地するかで決まる。ある程度の成功がセットになって、初めて“語れる人生”になるんだと思うよ。

