ハイスペの友人たちと会っていて思うのは人生は頭の良さよりも目標の高さと想いの強さで決まるということだ。特に想いの強さ。目標を高く持ち、想いを強くして生きれば、いつでも人生逆転できる。

ハイスペックな友人たちと時間を過ごしていて、いつも感じることがある。それは、最終的に人生を決めるのは「頭の良さ」じゃないということ。もちろん、地頭がいいに越したことはないし、知識や論理的思考は武器になる。でも、それだけで突き抜ける人間ってほとんどいないんよ。むしろ現実は逆で、目標の高さと、そこに対する想いの強さで結果が決まるケースの方が圧倒的に多い。

特に重要なのは「想いの強さ」だと思う。どれだけ高い目標を掲げても、想いが弱ければ途中で折れるケースがほとんどだから。逆に、想いが異常に強い人間は、多少能力が足りなくても、執念で埋めてくる。やり方を変え、環境を変え、人を巻き込みながら、最終的には形にしてしまう。この差は、スキルの差よりもはるかに大きい。

だから、人生はいつでも逆転できるんよ。年齢やこれまでの経歴に関係なく、「本気でやる」と決めて、目標を引き上げて、想いを強く持ち続けることができれば、流れは変わる。ただ、その「本気」は口で言うほど簡単じゃない。長い時間をかけて、何度も折れそうになりながら、それでもやり続ける覚悟が必要になる。

この話は、そのまま「誰と付き合うか問題」にもつながってくる。人は環境に引っ張られる生き物だから、誰と一緒にいるかで、基準も思考も行動も変わっていく。俺の場合、その中でも特に影響を受けたのが、ある大富豪の存在だ。その人は、自分にとって一つの「基準」になった。

正直に言うと、その人はいわゆるハイスペとは程遠いタイプだった。むしろ一般的な基準で見ればロースペに分類されると思う。経営も上手いとは言えないし、人間性にもかなりクセがあって、人がついてくるタイプではなかった。実際、会社の実務は弟さんが回しているような状態だったし、表面的に見れば「なぜこの人がここまでの資産を持てたのか」と不思議に思う人も多かったはず。

でも、それでもこの人が、世間が認めるほど圧倒的な結果を出してきたのは紛れもない事実。そこにヒントがあると思った。つまり、スペックやスキルの総合点で勝っているわけじゃない。どこか一点、もしくは数点で、異常なまでに突き抜けている。そして何より、「こうなる」というイメージと執着の強さが尋常じゃない。その部分においては、いわゆるハイスペックな人間よりも、よほど強烈だった。

俺はこの人とうまく付き合ってこられた。性格が激しい人、クセの強い人と関係を築くのは、昔からそこまで苦ではない。むしろ、そういう人間の方が面白いし、学べることも多い。扱いが難しい分、距離感やコミュニケーションの取り方を工夫する必要はあるが、その分リターンも大きい。

そして、その人の存在が、自分の目標設定にも大きな影響を与えた。「この人と同じくらいの資産を持つ」という具体的な基準ができた。52歳くらいまでにそこに到達する、というのが一つの目安だった。今、ちょうどその年齢に近づいているけど、正直なところ、まだ全然届いていない。

ただ、ここでこの目標は捨ててない。達成できていないから基準を下げるのではなく、時間軸をずらす。52歳で無理なら、62歳でいい。10年後に数百億円規模に到達する、と再設定するだけだ。目標そのものの高さは変えない。この「ズラし方」が重要だと思っている。

そもそも、目標は高い方がいい。多くの人は「現実的な目標」を立てようとするけど、それだと行動も思考もスケールしないものなんだわ。高い目標を掲げるからこそ、今の延長線では足りないと気づき、やり方を変えざるを得なくなる。その強制力が、自分を一段上のレベルに引き上げる。

結果的に、時間効率（タイパ）も、費用対効果（コスパ）も、高い目標の方が良くなることが多いのよ。小さくまとまろうとすると、結局は同じような努力をして、同じような時間を使って、小さな結果にしかならない。それなら最初から大きく取りにいった方がいい。

あとはシンプルで、その目標に対してどれだけ強くコミットできるか。それに尽きる。途中でブレないこと、言い訳しないこと、環境のせいにしないこと。やり続ける覚悟を持てるかどうか。

頭の良さよりも、目標の高さと想いの強さ。そして、その目標に対する執着。この3つが揃えば、人生はどのタイミングからでもひっくり返せる。逆に言えば、どれだけスペックが高くても、このどれかが欠けていれば、大きな結果にはつながらない。

結局、どこまでいっても問われるのは、「どこを目指しているのか」と「どれだけ本気なのか」なんだと思う。

６
おっさんの格差はとんでもなく大きい。清潔感、見た目年齢、コミニュケーション力、思考の柔軟さなど、長年の蓄積から大きな差が生じ、それが収入や社会的地位に反映されていく。若者は早いうちからこの現実を知り、イケてないおっさんにならないように頑張りんさいや。

おっさんの格差って、想像以上にエグいよ。若い頃は多少の差があっても、年齢である程度ごまかされるんだけど、。40代、50代と年を重ねていくと、それまでの積み重ねが全部表に出てくる。清潔感、見た目年齢、コミュニケーション力、思考の柔軟さ、このあたりにとんでもない差がついて、それがそのまま収入や社会的地位に反映されていく。

つまり、「どう年を取ったか」がその人の価値をほぼ決めてしまう。だから若いうちからこの現実を知っておいた方がいい。適当に生きていると、そのまま“イケてないおっさん”に一直線で突っ込むことになるからね。逆に、意識して積み上げていけば、年齢を重ねても価値を上げ続けることもできる。

まず何より大事なのは清潔感だよね。これはもう最低限のことだし、土俵に上がるための前提条件でしょ。鼻毛が出ている、歯が汚い、肌が荒れている、服がヨレている。この時点でアウト。さらに臭い問題。口臭や体臭があるのは論外だし、自分では気づきにくいからこそ、徹底的にケアしないといけない。おっさんって時点ですでにマイナスなのに、ここを甘く見ているおっさんは本当に多い。

俺自身も、見た目にはそれなりに気を使っている。白髪は今のところないけど、ハゲないようにケアはしている。抜け毛予防の薬を飲んだり、できることはやっている。こういうのは「まだ大丈夫」と思っているうちに差がつくからね。しかも最近は再生医療の進化もあって、5年、10年後には「ハゲ」という概念自体がかなり薄れていく可能性もあると思っている。最初はコストがかかるだろうけど、いずれ一般化していくだろう。そうなったときに、「何もしてこなかった人」と「早めに対応してきた人」とで、見た目の差はさらに広がる。

そもそも、おっさんを見て喜ぶ人なんて基本的にいないでしょ。若い頃にどれだけイケていたとしても、何も意識しなければ、ただの“キモいおじさん”になるだけだから。それを自覚して、実行に移せるかどうかなんだよね。多くのおっさんがやっていないから、意識するだけでも大きな差が出ると思うよ。

次に大事なのがコミュニケーション。典型的なのが、上から目線で物を言うおっさん。「君はここがダメだよね」とか、「俺の若い頃はさ」とか、頼まれてもいないのに説教を始めるやつ。あれは本当に嫌われるよね。本人は良かれと思って無自覚なのかもしれないけど、受け取る側からするとただのノイズでしかないんだわ。

基本はひたすら肯定でいいのよ。相手の話を受け止めて、「それいいね」と返す。欠点が見えても、それが実害をもたらすレベルでなければ、わざわざ指摘する必要はない。本当に伝えるべきことは限られているし、それ以外は言わない勇気も必要だと思う。「それ、今言う必要ある？」って一度立ち止まれるかどうかで、印象は大きく変わる。

俺は最近、半分遊びでキャバクラに行くことがあるんだけど、いわゆる素飲みって言われている“ワンセット乞食”にハマっている。女の子にドリンクも飲ませないし、指名もしないで初回だけで帰るってルールを徹底している（笑）。この前は名古屋のキャバに2人で行って、ワンセットで2万3000円くらいだったから安いなと思って2軒ハシゴしたんだけど、これがなかなか面白かった。その流れで六本木の店にも初めて行った。

そこで何をしているかというと、とにかく肯定の練習。キャバ嬢と話しながら、「それいいね」「その感じいいじゃん」とひたすらポジティブなリアクションを返す。極端な話、「この整形感いいね」くらいのノリでもいい（笑）。とにかく否定しない。そうすると、女の子はちゃんと乗ってくるし、場も自然と盛り上がる。

逆に、ああいう店って説教してくるおじさんが一定数いるらしいんだよね。だから余計に、ただ肯定するだけで差別化になるのよ。盛り上がってくると「指名してくれないんですか？」とか「ドリンクいいですか？」って言われるけど、「今日は彼にごちそうになってるから負担かけたくないんだよね」とか、「今日はそういう日じゃないんだわ」って軽くかわす。このやり取りも含めて、コミュニケーションの練習になる。

結局、おじさんって否定が多すぎるんだよ。変化を嫌がるし、「それは違う」ってすぐに言う。それが積み重なると、完全に“老害”になるんだよ。本人は気づかないまま、周りから距離を置かれていく。だからこそ、意識的に肯定するクセをつける必要がある。

現実として、若いやつの方が優秀な場面はどんどん増えている。情報量も多いし、吸収スピードも速い。その中で、「この人となら会ってもいい」と思ってもらえるおじさんでいられるかどうかか。臭い、食べ方が汚い、説教くさい、圧が強い。このどれか一つでも当てはまるだけで、若い人は普通に離れていく。

それで終わりじゃなくて、そういう状態になると、新しい情報も人脈も入ってこなくなるから、どんどん時代から取り残されていく。結果として、仕事の機会も減り、評価も下がっていく。こうして格差はさらに広がる。

だからこそ、見た目や清潔感といった「形」から入るのはアリだと思う。むしろ入口としては正しい。ただ、それだけじゃ足りない。最終的には態度や思考をアップデートしていかないと、近寄りがたい存在になる一方だから。

年齢を重ねること自体は止められない。でも、どういうおっさんになるかは選べる。積み上げてきたものが、そのまま外に出るのがこの年代だとしたら、なおさら日々の意識が重要になる。イケてるおっさんでいるか、ただの痛いおっさんになるか。その分岐は、思っている以上に小さな習慣の差で決まっていると思うのよ。

7
人生で足を踏み外したくなければスピリチュアル系の人間とは距離をとれ。若い頃はスピリチュアル系の友人もいたけど、結論的には全員がただの怠け者だったわ。彼らのアドバイスは的外れで適当でしかない。経営判断をスピリチュアル系の人間に委ねている会社はほとんど消えていくと思ってよい。

これは偏見で言っているわけじゃなくて、実体験からの結論なんだわ。若い頃は俺にもスピリチュアル寄りの知人がいたし、そういう世界に興味を持ったこともある。でも、長い時間をかけて見てきた結果として言えるのは、「深く関わるべきではない」ということ。

彼らの言っていることが、すべて間違っているとは言わない。中には一見もっともらしいこともあるし、耳触りのいい言葉も多い。ただ問題は、それが現実の行動や結果に結びつかないことがほとんどなのよ。結論から言うと、彼らのほとんどがただの怠け者だった。厳しい言い方になるけど、現実で勝負することから逃げているだけにしか見えなかったのよ。

スピリチュアルに傾倒していく人間って、どこかで「自分が努力しなくても何とかなる」という他力発想に寄っていく。運気だの波動だの、目に見えないものに原因を求めるようになると、現実の改善からどんどん遠ざかっていく。結果が出ない理由を外側に求める癖がつくから、いつまで経っても前に進まない。

当然、そういう人間のアドバイスは的外れになりやすいよね。現場で戦っていないから、具体性がないし、再現性もない。話を聞いている瞬間はそれっぽく感じても、実際は役に立たないということがほとんど。だから、経営判断のような重い意思決定を、そういう人間に委ねるのは本当に危険だと思うのよ。実際、スピリチュアル系に依存している会社で長く続いているところを、俺はほぼ見たことがない。

俺が人生の目標にしていた大富豪と仲良くなったとき、その周りにいたのも、まさにそういうスピリチュアル系の人間たちだった。成功している人の周りには、いろんな人が集まってくる。その中には、本気で価値を提供しようとしている人もいれば、ただ寄生しようとしている人もいる。後者の中に、スピリチュアル系の人間がかなりの割合で混ざっていたんだわ。

当時は「こういう世界もあるのか」と思いながら見ていたけど、時間が経って振り返ると、やっぱり半端者が多かった、というのが率直な感想だよね。口では大きなことを言うけど、実態が伴っていない。自分自身で何かを成し遂げたわけでもないのに、人に対して方向性を語ろうとする。その構造自体に無理があるんだわ。

もちろん、スピリチュアルや占いそのものを全否定するつもりはない。エンタメとして楽しむ分にはいいと思うし、気分転換や話のネタとして付き合うくらいなら問題ない。ただ、それを人生の判断基準にしてしまうのは完全に別の話だ。そこを履き違えると、一気におかしな方向に進んでいく。

特に危ないのは、「それっぽい言葉」を武器にして、人の意思決定に入り込んでくるタイプだ。やたらと抽象的で、反論しづらい言い回しを使ってくるけど、中身はスカスカだったりする。そういうものに影響されて、自分の判断軸を手放してしまうと、取り返しがつかなくなる。

さらに言えば、年上や実績のある人間に対して、スピリチュアルを根拠に上から物を言うようなタイプは、ほぼ例外なく消えていく。現実で結果を出している人間は、最終的には「再現性」と「実行力」でしか評価しないからだ。いくら言葉がきれいでも、結果が伴わなければ意味がない。そのシンプルな事実から逃げ続けている限り、当然、長くは持たないよね。

結局のところ、人生を前に進めるのは、地に足のついた行動の積み重ねしかないのよ。泥臭くても、再現性のあるやり方で、一つずつ結果を出していく。そのプロセスを飛ばして、「見えない力」に頼ろうとする時点で、勝負から降りているのと同じだと思う。

だからこそ、距離感が大事になる。完全に否定する必要はないが、深く入り込ませないこと。意思決定の中枢に置かないこと。そして、自分の軸は必ず現実に置くこと。この3つを守るだけでも、大きな失敗はかなり防げるはずだ。

楽な方向に流れたくなる気持ちは誰にでもあるよ。でも、その誘惑に名前をつけたのがスピリチュアルだとしたら、それに乗るかどうかは自分次第でしかない。厳しいようだけど、現実で勝ちたいなら、最後は現実で戦うしかない。そこから逃げないことが、結局いちばんの近道になるんじゃないかな。

8
人をみるときはシンプルに幸せそうかだけをみればいい。大きな仕事をしていたり、お金や社会的な地位があっても、幸せじゃなさそうな人と積極的に付き合おうとは思えないだろ。

結局、人は「どんな状態で生きているか」がすべてなんだよ。どれだけ大きな仕事をしていても、どれだけお金を持っていても、日常がしんどそうで、常に余裕がなくて顔つきが暗い人と一緒にいたいと思うかという話。答えはシンプルで、たいていの人は「NO」だと思う。

以前、ある知人の飲み会に参加したときのことなんだけど、その人が友達を一人連れてきた。初対面だったんだけど、会った瞬間から違和感があったのよ。何がどうというより、とにかく空気が重い。場の温度を一人で下げてしまうような雰囲気をまとっていた。

話を聞くと、ある企業に請われて社長として入って、第一線で活躍しているということだった。肩書きだけ見れば、いわゆる成功者の部類に入るんだと思う。でも、実際に話してみると、どこかうまくいっていない感じがにじみ出ていた。言葉の端々や表情、ちょっとした間の取り方に、それが出るんだよね。取り繕おうとしても、見る人が見れば、そういうものは隠しきれないんだよ。

唯一、その人が少し明るくなったのは、大学生の彼女の話をしているときだった。そこだけ妙にテンションが上がったの。でも正直、それがまたキモくて、違和感を覚えたよね。嬉しそうに話しているのはわかるんだけど、どこかズレているというか、痛々しさを感じてしまったんだよ。とにかく、全体としてバランスが悪いの。

その場では当たり障りない会話はしていたけど、内心では「こいつとは合わないな」とはっきり思ったよ。単純に一緒にいて楽しくないし、エネルギーを吸われる感覚があった。どれだけ立派な肩書きを持っていても、その一点で関わりたいとは思えなくなる。

で、後日。その飲み会にいた他の友人たちと話す機会があったんだけど、ほぼ全員が同じことを言ってきた。「千代目さん、あの人のこと嫌いですよね」「この前の彼、ヤバくなかったですか？」って。つまり、みんな同じ違和感を持っていたわけだ。誰かが言葉にしなくても、人は無意識に違和感を感じ取っているのよ。

これってすごく重要なポイントで、「幸せそうかどうか」って、意外とごまかせないんだよ。どれだけ取り繕っても、日々の積み重ねがそのまま空気として出る。逆に言えば、本当に楽しそうに生きている人は、それだけで周りを明るくするし、「また会いたい」と思わせる力がある。

もちろん、人生ずっと楽しいことばかりじゃないし、しんどい時期もある。ただ、その中でもどういうスタンスで生きているかは外に出る。余裕があるのか、追い詰められているのか。前向きに取り組んでいるのか、ただ耐えているだけなのか。その違いは、想像以上に周りに伝わる。

だから、人付き合いで迷ったらシンプルに考えればいい。「この人は幸せそうに生きているか？」
これだけでかなりフィルタリングできる。逆に言えば、自分自身も相手からそういう目で見られているということだ。どれだけ結果を出していても、「なんかしんどそうな人」になってしまったら、人は離れていく。

最終的に人が集まるのは、「一緒にいて気分がよくなる人」だと思う。そこに肩書きや実績が乗ってくるとさらに強いけど、土台はあくまでその人の状態だ。

楽しそうに生きているかどうか。幸せそうに見えるかどうか。これは単なる感情論じゃなくて、人間関係やビジネスにも直結する、かなり本質的な指標だと思う。だからこそ、他人を見るときも、自分を見直すときも、この軸は持っておいた方がいい。

