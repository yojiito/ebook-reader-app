でも、こういうのも含めて人生だなって思うよね。あのとき焦って無理に関係を取り戻そうとしなくてよかった。結局、人間関係ってタイミングなんだよ。無理やりどうにかしようとしてもダメなときはダメ。でも、流れが来たときには自然と戻る。

さっきの話じゃないけど、「輝いているかどうか」っていうのはやっぱり重要なんだよね。親としてどうこうじゃなくて、一人の人間として魅力があるかどうか。そこをちゃんとやっていれば、結果的に人は戻ってくる。これは子どもに限らず、人間関係全般に言えることだと思うよ。だから結局、やることはシンプルで、「自分の人生をちゃんと生きること」なんだよね。そうすれば、必要なものはあとからついてくる。

