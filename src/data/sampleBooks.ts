おれ、親の会社を引き継ぎ、新規事業立ち上げて育てて売却した。そうやって親の老後資金を渡してから距離を置いたよ。子供として親に対してやるべきことをやってから独立してる。誰か褒めてくれ。笑

俺は家族と仕事をするのが向いてなかった。これ、やってみてはっきり分かったこと。だから家業を売却した後は、自分でゼロから事業を始めた。親と一緒にやってたら、たぶんどこかで壊れてたと思うよ。今振り返ると、うちの両親はおそらく毒親だったんだよね。だからこそ、距離を取るっていう選択が必要だった。これって長期的に見ると正解だったと思っている。一緒にいることで消耗するなら、離れた方がいい。

この話で言いたいのは、「一家の長の器量」なんだよね。うちのオヤジはそこが決定的に欠けていた。だから、こっちがめちゃくちゃ苦労した。もし器のある人だったら、後継者の育て方も含めて、もっとスムーズにいってたと思う。でも現実はそうじゃなかったから、「この人たちとやってもうまくいかないな」ってずっと思ってたし、「早く抜けたい」と思い続けてた。

世の中には、創業家が何代も社長を継承しているような何百年も続く老舗企業とかあるけど、正直なところ「それってそんなに重要か？」って思っている。創業100年とか200年とか言われても、「だから何ですか？」っていう感覚なんだよね。今の時代、事業サイクルはめちゃくちゃ早い。だったら、一つの事業に固執するよりも、育てて売って、また次をやるっていう方が合理的なケースも多い。長く続けること自体が目的になってしまうと、本質を見失う。会社って、続けるためにあるんじゃなくて、価値を生むためにあるからね。だから、「継ぐこと」にこだわる必要はないし、「続けること」にもそこまで意味はないと思っているんだわ。

