ヒルトン創業者がインタビューで「たかがベルボーイがなぜホテル王になれたのですか？」と聞かれたとき「ベルボーイがホテル王になったのではなく、ホテル王がベルボーイからはじめたのだ」と答えたという逸話の中に、人生を逆算で考える効果の全てが、たたみ込まれていると思っている。

この一言に、人生の考え方の本質が詰まっていると思うんだよね。

多くの人は「今の自分」からスタートして未来を考える。でもそれだと発想が小さくなる。そうじゃなくて、「最終的にどうなっているか」を先に決めて、そこから逆算して現在の行動を決めるべきなんだよ。

ホテル王になる人間は、最初からホテル王としての視点で動いている。たまたま最初のポジションがベルボーイだっただけで、やっていることの解像度や意思決定の基準は最初から違う。例えば、今飲食店でバイトしている人でも、将来、海外で展開できるチェーン店を作って行くって目標のもと働いていたら、考え方や働き方がほかのバイトとは違ってくるでしょ。

だから重要なのは、目標設定の解像度。「成功したい」みたいな曖昧なものではなく、

・どのレベルまで行くのか
・いくら稼ぐのか
・どんな状態を実現するのか

ここを具体的な数字やイメージで持つこと。そこまで決めてしまえば、あとは逆算してやるべきことを積み上げていくだけになる。途中で多少ブレることはあっても、方向性が定まっているから大きく外すことはない。

逆に言うと、ここが曖昧なままだと、目の前の選択を全部“なんとなく”で決めることになるから、気づいたら全然違う場所にいる、ということが普通に起こる。
最初にどれだけ高い目標を設定できるか。そして、それを前提に日々の行動を組み立てられるか。これだけで、数年後に見える景色はまったく変わってくると思うよ。
